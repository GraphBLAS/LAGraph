double matrix_difference(GrB_Matrix JC, const double *ref, GrB_Matrix A_mask, bool all_pairs) 
{
	GrB_Matrix JCref = NULL, Diff = NULL ;
	GrB_Index N = 0;
	OK (GrB_Matrix_nrows (&N, JC)) ;
	OK (GrB_Matrix_new (&JCref, GrB_FP64, N, N)) ;
	GrB_Index k = 0 ;
	for (GrB_Index i = 0 ; i < N ; i++) {
		for (GrB_Index j = i ; j < N ; j++) {
			double v = ref[k++] ;
			if (v != 0.0f) {
				OK (GrB_Matrix_setElement_FP64 (JCref, v, i, j)) ;
			}
		}
	}
	OK (GrB_Matrix_new (&Diff, GrB_FP64, N, N)) ;
	if (all_pairs)
	{
		OK (GrB_eWiseAdd (Diff, NULL, NULL, GrB_MINUS_FP64, JC, JCref, NULL)) ;
	}
	else
	{
		OK (GrB_eWiseAdd (Diff, A_mask, NULL, GrB_MINUS_FP64, JC, JCref, NULL)) ;
	}
	OK (GrB_apply (Diff, NULL, NULL, GrB_ABS_FP64, Diff, NULL)) ; //absolute value
	float err = 0 ;
	OK (GrB_reduce (&err, NULL, GrB_MAX_MONOID_FP64, Diff, NULL)) ; //get max
	OK (GrB_free (&Diff)) ;
	OK (GrB_free (&JCref)) ;
	return err ;
}


void run_jaccard (const char *input_mat, const double *results)
{

	GrB_Matrix A = NULL;
	GrB_Index n; 

	// create the graph
	snprintf (filename, LEN, LG_DATA_DIR "%s", input_mat) ;
	FILE *f = fopen (filename, "r") ;
	TEST_CHECK (f != NULL) ;
	OK (LAGraph_MMRead (&A, f, msg)) ;
	OK (fclose (f)) ;

	OK (LAGraph_New (&G, &A, LAGraph_ADJACENCY_UNDIRECTED, msg)) ;
	OK (LAGraph_DeleteSelfEdges (G, msg)) ;
	OK (LAGraph_Cached_OutDegree (G, msg)) ;       
	TEST_CHECK (A == NULL) ;    

	bool all_pairs;
	GrB_Matrix A_mask = G->A;
	double err;

	//--------------------------------------------------------------------------
	// Experiment 1: All-pairs Jaccard similarity
	//--------------------------------------------------------------------------
	printf("\nDataset : \"%s\" \nComputing Jaccard Similarity for all pairs\n", input_mat);
	all_pairs = true;	// if false it only computes jaccard weights(jaccard similarity for neighbors)
	OK (LAGr_Jaccard (&JC, G, all_pairs, msg)) ;
	//check for correctness
	err = matrix_difference (JC, results, A_mask, all_pairs) ;
	TEST_CHECK (err < 1e-6) ;   
	TEST_MSG ("Test not passed. max abs error = %e\n", err);
	printf("Test passed with max abs error = %e\n", err) ;
	OK(GrB_free(&JC)); 
	JC = NULL;

	//--------------------------------------------------------------------------
	// Experiment 2: Jaccard weights (neighbors only)
	//--------------------------------------------------------------------------
	printf("\n Dataset : \"%s\" \nComputing Jaccard Weights for existing edges\n", input_mat);
	all_pairs = false;	// if false it only computes jaccard weights(jaccard similarity for neighbors)
	OK (LAGr_Jaccard (&JC, G, all_pairs, msg)) ;
	//check for correctness
	err = matrix_difference (JC, results, A_mask, all_pairs) ;
	TEST_CHECK (err < 1e-6) ;   // adjust tolerance if needed
	TEST_MSG ("Test not passed. max abs error = %e\n", err);
	printf("Test passed with max abs error = %e\n", err) ;
	TEST_CHECK(0 == GrB_free(&JC));

	// free everything
	OK(LAGraph_Delete(&G, msg));
}

void test_Jaccard (void)
{

	LAGraph_Init (msg) ;

	run_jaccard ("A.mtx", A_jaccard_allpairs) ;

	run_jaccard ("karate.mtx", karate_jaccard_allpairs) ;

	run_jaccard ("ldbc-undirected-example-bool.mtx", ldbc_jaccard_allpairs) ;

	LAGraph_Finalize (msg) ;
}

